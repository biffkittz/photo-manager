#!/usr/bin/env bash
# Generates throwaway DEVELOPMENT secrets and stores them in:
#   - dotnet user-secrets for the API, worker and migrator (used by `dotnet run` and VS Code debugging)
#   - .env at the repository root (used by `docker compose --profile app`), permissions 600
# Existing values are kept unless --force is passed. Values are never printed.
#
# Optional, picked up from your environment if set (needed only to sign in locally):
#   GITHUB_CLIENT_ID, GITHUB_CLIENT_SECRET   GitHub OAuth app with callback http://localhost:5080/signin-github
#   GITHUB_USER_ID                           your numeric GitHub id: curl -s https://api.github.com/users/<login> | jq .id
#   GOOGLE_CLIENT_ID, GOOGLE_CLIENT_SECRET   Google OAuth client (web application) with the authorized redirect URI
#                                            http://localhost:5080/signin-google, to try invites locally (optional)
#
# NEVER use production secrets here; production secrets live only in Azure Key Vault.
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
api="$repo_root/app/backend/src/PhotoManager.Api"
worker="$repo_root/app/backend/src/PhotoManager.Worker"
env_file="$repo_root/.env"
force=false
[[ "${1:-}" == "--force" ]] && force=true

command -v dotnet >/dev/null || { echo "dotnet SDK not found (see docs/development.md)" >&2; exit 1; }

random_b64() { head -c "$1" /dev/urandom | base64 | tr -d '\n'; }

# Reuse values from an existing .env so user-secrets and compose stay consistent.
existing() { [[ -f "$env_file" ]] && grep -E "^$1=" "$env_file" | head -1 | cut -d= -f2- || true; }

web_key="$(existing CRYPTO_WEB_KEY)"; payload_key="$(existing TEMPORAL_PAYLOAD_KEY)"; archive_password="$(existing DEV_ARCHIVE_PASSWORD)"
if $force || [[ -z "$web_key" ]]; then web_key="$(random_b64 32)"; fi
if $force || [[ -z "$payload_key" ]]; then payload_key="$(random_b64 32)"; fi
if $force || [[ -z "$archive_password" ]]; then archive_password="dev-only-$(random_b64 24)"; fi

set_secret() { dotnet user-secrets set "$2" "$3" --project "$1" >/dev/null; }

for project in "$api" "$worker"; do
  set_secret "$project" "Crypto:WebKey" "$web_key"
  set_secret "$project" "Temporal:PayloadKey" "$payload_key"
done
# Only the worker gets the archive password (split-key design; the API refuses to start with it).
set_secret "$worker" "Crypto:ArchivePassword" "$archive_password"

if [[ -n "${GITHUB_CLIENT_ID:-}" && -n "${GITHUB_CLIENT_SECRET:-}" ]]; then
  set_secret "$api" "Auth:GitHubClientId" "$GITHUB_CLIENT_ID"
  set_secret "$api" "Auth:GitHubClientSecret" "$GITHUB_CLIENT_SECRET"
fi
if [[ -n "${GOOGLE_CLIENT_ID:-}" && -n "${GOOGLE_CLIENT_SECRET:-}" ]]; then
  set_secret "$api" "Auth:GoogleClientId" "$GOOGLE_CLIENT_ID"
  set_secret "$api" "Auth:GoogleClientSecret" "$GOOGLE_CLIENT_SECRET"
fi
if [[ -n "${GITHUB_USER_ID:-}" ]]; then
  set_secret "$api" "Auth:Users:0:GitHubId" "$GITHUB_USER_ID"
  set_secret "$api" "Auth:Users:0:Role" "Admin"
fi

# Read the values to keep *before* rewriting the file: the redirection below truncates it before the
# heredoc is expanded, so reading .env inside the heredoc would always see an empty file.
github_client_id="${GITHUB_CLIENT_ID:-$(existing GITHUB_CLIENT_ID)}"
github_client_secret="${GITHUB_CLIENT_SECRET:-$(existing GITHUB_CLIENT_SECRET)}"
github_user_id="${GITHUB_USER_ID:-$(existing GITHUB_USER_ID)}"
google_client_id="${GOOGLE_CLIENT_ID:-$(existing GOOGLE_CLIENT_ID)}"
google_client_secret="${GOOGLE_CLIENT_SECRET:-$(existing GOOGLE_CLIENT_SECRET)}"

# Written to a private temp file and moved into place, so an interrupted run never leaves a half-written .env.
umask 077
tmp_env="$(mktemp "$env_file.XXXXXX")"
cat > "$tmp_env" <<ENV
# Generated by scripts/dev-secrets.sh - local development only, never commit (gitignored).
CRYPTO_WEB_KEY=$web_key
TEMPORAL_PAYLOAD_KEY=$payload_key
DEV_ARCHIVE_PASSWORD=$archive_password
GITHUB_CLIENT_ID=$github_client_id
GITHUB_CLIENT_SECRET=$github_client_secret
GITHUB_USER_ID=$github_user_id
GOOGLE_CLIENT_ID=$google_client_id
GOOGLE_CLIENT_SECRET=$google_client_secret
GEMINI_USE_FAKE=true
ENV
chmod 600 "$tmp_env"
mv "$tmp_env" "$env_file"
echo "Development secrets are in dotnet user-secrets and $env_file (values not shown)."
