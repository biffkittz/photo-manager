import { admin, expect, expectAccessible, mockSession, pixelPng, test } from './fixtures'

const photos = [
  {
    id: 'p1',
    fileName: 'IMG_1.jpg',
    description: 'woman and boy smiling on the beach',
    uploadedAt: '2024-07-04T12:00:00Z',
    takenAt: '2024-07-04T11:00:00Z',
    width: 800,
    height: 600,
    renditionState: 'Ready',
    renditionVersion: 1,
  },
  {
    id: 'p2',
    fileName: 'IMG_2.jpg',
    description: 'dog running in the snow',
    uploadedAt: '2024-07-03T12:00:00Z',
    takenAt: null,
    width: 800,
    height: 600,
    renditionState: 'Ready',
    renditionVersion: 1,
  },
]

test.beforeEach(async ({ page }) => {
  await mockSession(page, admin)
  await page.route('**/api/photos?*', (route) => {
    const q = new URL(route.request().url()).searchParams.get('q') ?? ''
    const items = photos.filter((p) => p.description.includes(q))
    return route.fulfill({ json: { items, nextCursor: null } })
  })
  await page.route(/\/api\/photos\/p\d\/(thumbnail|preview)/, (route) =>
    route.fulfill({ body: pixelPng, contentType: 'image/png' }),
  )
  await page.route(/\/api\/photos\/p\d$/, (route) => {
    const photo = photos.find((p) => route.request().url().endsWith(p.id))!
    return route.fulfill({
      json: {
        ...photo,
        descriptionSource: 'Gemini',
        descriptionState: 'Ready',
        tags: ['beach'],
        contentType: 'image/jpeg',
        sizeBytes: 1234,
        uploadedBy: 'octo',
        status: 'Ready',
        statusDetail: null,
        encryptionFormat: 'V2',
        source: 'Upload',
      },
    })
  })
})

test('browses, searches and opens a photo with the keyboard', async ({ page }) => {
  await page.goto('/gallery')
  await expect(page.getByRole('list', { name: 'Photos' }).getByRole('listitem')).toHaveCount(2)
  await expectAccessible(page)

  const search = page.getByRole('searchbox', { name: 'Search photos' })
  await search.fill('sno')
  await expect(page).toHaveURL(/q=sno/)
  await expect(page.getByRole('list', { name: 'Photos' }).getByRole('listitem')).toHaveCount(1)
  // The results arriving (and ?q= changing) must not take focus away: typing carries on.
  await expect(search).toBeFocused()
  await page.keyboard.type('w')
  await expect(page).toHaveURL(/q=snow/)
  await expect(search).toBeFocused()
  await expect(search).toHaveValue('snow')

  await page.getByRole('button', { name: 'Open dog running in the snow' }).press('Enter')
  const dialog = page.getByRole('dialog', { name: 'dog running in the snow' })
  await expect(dialog).toBeVisible()
  await expect(dialog.getByText('Generated by Gemini')).toBeVisible()
  await expectAccessible(page)

  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  await expect(page).toHaveURL(/\/gallery\?q=snow$/)
})

test('photos are deep-linkable', async ({ page }) => {
  await page.goto('/gallery/photos/p1')
  await expect(
    page.getByRole('dialog', { name: 'woman and boy smiling on the beach' }),
  ).toBeVisible()
})
